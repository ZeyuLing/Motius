"""Compose actual Blender screen takes using an explicit, auditable edit list.

No motion interpolation or time scaling is used. Waiting is removed through
labelled cuts; the opening's 750 visible source counters are checked separately.
"""
from __future__ import annotations
import argparse
import json
import subprocess
from pathlib import Path

FONT = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('manifest', type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    manifest = json.loads(args.manifest.read_text())
    work = args.output.parent/'product-release-edit'
    work.mkdir(parents=True, exist_ok=True)
    output_clips = []
    timeline = []
    position = 0.
    source_durations = {}
    for index, segment in enumerate(manifest['segments']):
        source = Path(segment['source']).resolve()
        duration = float(segment['duration'])
        if duration <= 0 or not source.is_file():
            raise ValueError(f'Invalid segment {index}')
        if source not in source_durations:
            value=json.loads(subprocess.check_output(['ffprobe','-v','error','-show_entries',
                'format=duration','-of','json',str(source)],text=True))
            source_durations[source]=float(value['format']['duration'])
        if float(segment['start']) < 0 or float(segment['start'])+duration > source_durations[source]+.005:
            raise ValueError(f'Segment {index} exceeds its recorded source duration')
        filters = [f'trim=duration={duration}', 'setpts=PTS-STARTPTS', 'fps=30', 'setsar=1']
        if segment.get('hold'):
            filters.append(f"tpad=stop_mode=clone:stop_duration={float(segment['hold'])}")
        for number, label in enumerate(segment.get('labels', [])):
            textfile = work/f'{index:02d}-{number}.txt'
            textfile.write_text(label['text'])
            # Paths are generated by this tool. textfile avoids quoting copy as
            # executable filter syntax; each heading has a bounded display time.
            path = str(textfile.resolve()).replace('\\', '\\\\').replace(':', '\\:').replace("'", "\\'")
            start = float(label.get('start', 0))
            end = float(label.get('end', duration))
            alpha = f"if(lt(t,{start}+.3),(t-{start})/.3,if(gt(t,{end}-.3),({end}-t)/.3,1))"
            filters.append(f"drawtext=fontfile={FONT}:textfile='{path}':"
                f"x={int(label.get('x', 56))}:y={int(label.get('y', 135))}:"
                f"fontsize={int(label.get('size', 44))}:fontcolor={label.get('color', 'white')}:"
                f"shadowcolor=black@0.55:shadowx=1:shadowy=2:line_spacing=10:"
                f"alpha='{alpha}':enable='between(t,{start},{end})'")
        if segment.get('waiting_condensed'):
            filters.append("drawtext=fontfile="+FONT+":text='Processing time condensed':"
                "x=56:y=920:fontsize=21:fontcolor=white:shadowcolor=black@0.7:shadowx=1:shadowy=1")
        target = work/f'{index:02d}.mp4'
        subprocess.run(['ffmpeg', '-v', 'error', '-ss', str(segment['start']), '-i', str(source),
            '-t', str(duration+float(segment.get('hold', 0))), '-an', '-vf', ','.join(filters),
            '-c:v', 'libx264', '-threads', '4', '-preset', 'fast', '-crf', '18',
            '-pix_fmt', 'yuv420p', '-movflags', '+faststart', '-y', str(target)], check=True)
        output_clips.append(target)
        length = duration+float(segment.get('hold', 0))
        timeline.append({**segment, 'timeline_start':position, 'timeline_end':position+length})
        position += length
    concat = work/'concat.txt'
    concat.write_text(''.join("file '"+str(path.resolve()).replace("'", "'\\''")+"'\n" for path in output_clips))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(['ffmpeg', '-v', 'error', '-f', 'concat', '-safe', '0', '-i', str(concat),
        '-c', 'copy', '-movflags', '+faststart', '-y', str(args.output)], check=True)
    (work/'timeline.json').write_text(json.dumps(timeline, indent=2))
    print(json.dumps({'output':str(args.output.resolve()), 'seconds':position,
                      'segments':len(timeline), 'motion_time_scaled':False}))


if __name__ == '__main__':
    main()
